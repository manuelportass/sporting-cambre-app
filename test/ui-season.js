'use strict';
// Recorrido visual con el listado real 2026/27 (sin datos de carga inventados).
const os = require('os'), fs = require('fs'), path = require('path');
const { chromium } = require('playwright');
const out = path.resolve(process.argv[2] || 'shots-season');
fs.mkdirSync(out, { recursive: true });
process.env.DATA_DIR = fs.mkdtempSync(path.join(os.tmpdir(), 'scpf-uis-'));
process.env.SETUP_CODE = '333333';
const { createApp } = require('../server/index');
(async () => {
  const server = createApp().listen(0); await new Promise(r => server.on('listening', r));
  const base = `http://127.0.0.1:${server.address().port}`;
  const browser = await chromium.launch();
  const errors = [];
  const watch = p => { p.on('pageerror', e => errors.push(e.message)); p.on('console', m => m.type() === 'error' && errors.push(m.text())); };
  const shot = async (p, n, full = true) => { await p.waitForTimeout(600); await p.screenshot({ path: path.join(out, n + '.png'), fullPage: full }); };
  const ctx = await browser.newContext({ viewport: { width: 1360, height: 900 }, locale: 'es-ES' });
  const page = await ctx.newPage(); watch(page);
  await page.goto(base); await shot(page, '00-setup');
  await page.fill('input[inputmode=numeric]', '333333');
  const pins = page.locator('input[type=password]'); await pins.nth(0).fill('cambre2026'); await pins.nth(1).fill('cambre2026');
  await page.click('button:has-text("Crear cuenta")'); await page.waitForSelector('.tile');
  await shot(page, '01-inicio-vacio');
  await page.goto(base + '/jugadores'); await page.click('button:has-text("Cargar listado 2026/27")');
  await page.waitForSelector('text=Franjas del gimnasio'); await shot(page, '02-carga-temporada', false);
  await page.click('button:has-text("Crear franjas y ver vista previa")'); await page.waitForSelector('text=Guardar 105'); await shot(page, '03-vista-previa', false);
  await page.click('button:has-text("Guardar 105")'); await page.waitForSelector('text=69 jugadores'); await shot(page, '04-jugadores');
  await page.goto(base + '/'); await page.waitForLoadState('networkidle'); await shot(page, '05-inicio');
  await page.goto(base + '/gimnasio'); await page.waitForLoadState('networkidle'); await shot(page, '06-asistencia');
  await page.click('.seg button:has-text("Jueves")'); await page.waitForLoadState('networkidle'); await shot(page, '07-asistencia-jueves');
  await page.goto(base + '/primer-equipo'); await page.waitForLoadState('networkidle'); await shot(page, '08-primer-equipo');
  await page.goto(base + '/primer-equipo/cuentas'); await page.waitForLoadState('networkidle');
  await page.locator('tr:has-text("Bruno González") button:has-text("Crear cuenta")').click();
  await page.waitForSelector('text=PIN provisional'); const pin = (await page.locator('.modal .card div').nth(3).textContent()).trim();
  await shot(page, '09-credenciales', false);
  await page.click('button:has-text("Hecho")');
  await page.goto(base + '/configuracion'); await page.waitForLoadState('networkidle'); await shot(page, '10-config-club');
  const m = await browser.newContext({ viewport: { width: 1360, height: 900 } }); const lp = await m.newPage(); watch(lp);
  await lp.goto(base); await shot(lp, '11-login', false);
  const pc = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, locale: 'es-ES' });
  const pp = await pc.newPage(); watch(pp);
  await pp.goto(base); await shot(pp, '20-login-movil', false);
  await pp.fill('input[autocomplete=username]', 'bruno gonzalez'); await pp.fill('input[type=password]', pin); await pp.click('button:has-text("Entrar")');
  await pp.waitForSelector('text=Crea tu PIN'); const pw = pp.locator('input[type=password]');
  await pw.nth(0).fill(pin); await pw.nth(1).fill('9753'); await pw.nth(2).fill('9753'); await pp.click('button:has-text("Guardar PIN")');
  await pp.waitForSelector('text=Wellness'); await shot(pp, '21-jugador-inicio', false);
  await pp.click('button.action:has-text("RPE")'); await shot(pp, '22-rpe', true);
  const mob = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, storageState: await ctx.storageState() });
  const ma = await mob.newPage(); watch(ma); await ma.goto(base + '/gimnasio'); await ma.waitForLoadState('networkidle'); await shot(ma, '23-admin-movil', false);
  await browser.close(); server.close();
  console.log(errors.length ? 'ERRORES:\n' + errors.join('\n') : 'Sin errores de consola.');
})().catch(e => { console.error(e); process.exit(1); });
