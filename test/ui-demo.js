'use strict';
// Prueba de la versión de prueba (HTML único) con una política CSP estricta, sin red.
const fs = require('fs'), path = require('path'), http = require('http');
const { chromium } = require('playwright');
const out = path.resolve(process.argv[2] || 'shots-demo'); fs.mkdirSync(out, { recursive: true });
let html = fs.readFileSync(path.join(__dirname, '..', 'client', 'dist-demo', 'demo.html'), 'utf8');
const CSP = "default-src 'none'; script-src 'unsafe-inline'; style-src 'unsafe-inline'; font-src data:; img-src data: blob:; connect-src 'none'";
html = html.replace('<head>', `<head><meta http-equiv="Content-Security-Policy" content="${CSP}">`);
const server = http.createServer((q, r) => { r.setHeader('content-type', 'text/html; charset=utf-8'); r.end(html); }).listen(0);
(async () => {
  const base = `http://127.0.0.1:${server.address().port}/artifact`;
  const browser = await chromium.launch();
  const errors = [];
  const ctx = await browser.newContext({ viewport: { width: 1360, height: 900 }, locale: 'es-ES' });
  const page = await ctx.newPage();
  page.on('pageerror', e => errors.push('[pageerror] ' + e.message));
  page.on('console', m => m.type() === 'error' && errors.push('[console] ' + m.text()));
  page.on('request', r => { if (!r.url().startsWith(base) && !r.url().startsWith('data:') && !r.url().startsWith('blob:')) errors.push('[red] ' + r.url()); });
  const shot = async (n, full = true) => { await page.waitForTimeout(500); await page.screenshot({ path: path.join(out, n + '.png'), fullPage: full }); };
  const t0 = Date.now();
  await page.goto(base); await page.waitForSelector('.tile', { timeout: 60000 });
  console.log('Arranque:', Date.now() - t0, 'ms');
  await shot('01-inicio');
  await page.click('nav >> text=Jugadores'); await page.click('button[aria-label="Más opciones"]'); await page.click('button:has-text("Cargar listado 2026/27")');
  await page.click('button:has-text("Crear franjas y ver vista previa")'); await page.waitForSelector('text=Guardar 105');
  await page.click('button:has-text("Guardar 105")'); await page.waitForSelector('text=105 de 105'); await shot('02-jugadores');
  await page.click('nav >> text=Gimnasio'); await page.waitForSelector('.tile'); await shot('03a-gimnasio');
  await page.locator('.tile').first().click(); await page.waitForSelector('.statusbtns');
  await page.locator('.statusbtns').first().locator('button').first().click(); await page.waitForTimeout(400); await shot('03b-franja');
  await page.click('button.back'); await page.click('button:has-text("Informe semanal")'); await page.waitForTimeout(800); await shot('04-informe');
  await page.click('nav >> text=Primer equipo'); await page.waitForSelector('.tile'); await shot('04b-primer-equipo');
  await page.click('.tile:has-text("Cuentas")'); await page.locator('.lrow:has-text("Bruno González") button:has-text("Crear cuenta")').click();
  await page.waitForSelector('text=PIN provisional'); const pin = (await page.locator('.modal .card div').nth(3).textContent()).trim();
  await page.click('button:has-text("Hecho")');
  // Persistencia: recargar y comprobar que siguen los datos
  await page.reload(); await page.waitForSelector('.tile', { timeout: 60000 });
  await page.click('nav >> text=Jugadores'); await page.waitForSelector('text=105 de 105');
  await page.click('button:has-text("Salir")'); await page.waitForSelector('text=Versión de prueba · Preparador'); await shot('05-login', false);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.fill('input[autocomplete=username]', 'Bruno González'); await page.fill('input[type=password]', pin); await page.click('button:has-text("Entrar")');
  await page.waitForSelector('text=Crea tu PIN'); const pw = page.locator('input[type=password]');
  await pw.nth(0).fill(pin); await pw.nth(1).fill('2468'); await pw.nth(2).fill('2468'); await page.click('button:has-text("Guardar PIN")');
  await page.waitForSelector('button.action'); await page.click('button.action:has-text("Wellness")');
  for (const g of await page.locator('.scale').all()) await g.locator('button').nth(3).click();
  await page.fill('textarea', 'Bien'); await page.click('button:has-text("Enviar")'); await page.waitForSelector('text=Wellness guardado'); await shot('06-jugador', false);
  const st = await page.evaluate(async () => (await fetch('/api/players')).status);
  if (st !== 403) errors.push('Permisos: jugador ve /players → ' + st);
  await browser.close(); server.close();
  console.log(errors.length ? 'ERRORES:\n' + errors.join('\n') : 'Sin errores.');
})().catch(e => { console.error(e); server.close(); process.exit(1); });
